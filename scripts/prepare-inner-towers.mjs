import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
const source=process.argv[2];if(!source)throw Error('Pass the folder containing the supplied tower PNGs');
const out='src/ui/arena/assets/inner-towers';await mkdir(out,{recursive:true});const manifest=[],ruins={};
for(const [team,color]of [['ally','синяя'],['enemy','красная']])for(const [stage,suffix]of [['full',''],['damaged',' половина хп'],['ruins',' разрушена']]){
  const name=`Башня ${color} 18хп${suffix}.png`,bytes=await readFile(join(source,name));
  const original=await sharp(bytes).metadata();if(!original.hasAlpha)throw Error(`Expected transparent PNG: ${name}`);
  let image=sharp(bytes),crop={left:18,top:12,width:1026,height:1440};
  if(stage==='ruins'){
    const {data,info}=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});let x0=info.width,y0=info.height,x1=0,y1=0;
    for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>16){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
    crop={left:Math.max(0,x0-2),top:Math.max(0,y0-2),width:Math.min(info.width,x1+3)-Math.max(0,x0-2),height:Math.min(info.height,y1+3)-Math.max(0,y0-2)};
    ruins[team]={aspect:crop.width/crop.height,anchorX:((team==='ally'?635:607)-crop.left)/crop.width};
  }
  const file=`tower-18-${team}-${stage}.webp`;
  const result=await image.extract(crop).resize({height:stage==='ruins'?500:800}).webp({quality:94,alphaQuality:100,effort:5}).toFile(join(out,file));
  manifest.push({file,source:name,sourceSha256:createHash('sha256').update(bytes).digest('hex'),crop,width:result.width,height:result.height,bytes:result.size});
}
await writeFile(join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile('src/ui/arena/inner-tower-meta.js',`// Generated by scripts/prepare-inner-towers.mjs from the supplied PNGs.\nexport const INNER_TOWER_META = ${JSON.stringify({aspect:1026/1440,anchorX:(524-18)/1026,ruins},null,2)};\n`);
console.log(`Prepared ${manifest.length} transparent inner tower assets (${Math.round(manifest.reduce((sum,m)=>sum+m.bytes,0)/1024)} KiB)`);
